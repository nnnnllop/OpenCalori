def main():
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    if os.path.exists(OUT_PATH):
        os.remove(OUT_PATH)

    conn = sqlite3.connect(OUT_PATH)
    cur = conn.cursor()

    # Room master table
    cur.executescript(SCHEMA)
    cur.executescript(TRIGGERS)

    # Insert products
    cur.executemany(
        "INSERT INTO products (id, name, caloriesPer100g, proteinPer100g, fatPer100g, carbsPer100g) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        [(i + 1, name, kcal, p, f, c) for i, (name, kcal, p, f, c) in enumerate(PRODUCTS)]
    )

    # Populate FTS index manually (triggers only fire on new inserts after table exists,
    # but since FTS table was created before inserts, triggers already fired — however
    # content= tables need explicit rebuild for existing rows).
    cur.execute("INSERT INTO products_fts(products_fts) VALUES('rebuild')")

    # Set identity hash
    cur.execute("DELETE FROM room_master_table")
    cur.execute("INSERT INTO room_master_table (id, identity_hash) VALUES (42, ?)", (ROOM_IDENTITY_HASH,))

    conn.commit()
    conn.close()

    size_kb = os.path.getsize(OUT_PATH) / 1024
    print(f"Created {OUT_PATH} ({size_kb:.1f} KB, {len(PRODUCTS)} products)")

    if ROOM_IDENTITY_HASH == "REPLACE_ME":
        print("\n[WARNING] ROOM_IDENTITY_HASH is a placeholder.")
        print("   Build the app once (assembleDebug) -- Room will report the expected hash.")
        print("   Then paste it into ROOM_IDENTITY_HASH and re-run this script.")
        sys.exit(2)


if __name__ == "__main__":
    main()
